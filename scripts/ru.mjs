const LETTERS = {
  a: 'а', i: 'и', u: 'у', o: 'о',
  k: 'к', s: 'с', t: 'т', n: 'н', h: 'х', m: 'м', r: 'р', g: 'г', z: 'з', d: 'д', b: 'б', p: 'п',
  f: 'ф', w: 'в', y: 'й', v: 'в', l: 'л', j: 'дж', c: 'к', x: 'кс', q: 'к',
}
const VOWELS = new Set(['a', 'e', 'i', 'o', 'u'])

function transliterateWord(word) {
  const w = word
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
  let out = ''
  let i = 0
  while (i < w.length) {
    const syl = SYLLABLES.find(([lat]) => w.startsWith(lat, i))
    if (syl) {
      out += syl[1]
      i += syl[0].length
      continue
    }
    const ch = w[i]
    const prev = w[i - 1]
    if (ch === 'e') out += i === 0 || VOWELS.has(prev) ? 'э' : 'е'
    else if (ch === 'i' && prev && 'aeo'.includes(prev) && !VOWELS.has(w[i + 1] ?? '')) out += 'й'
    else if (ch === 'y' && !VOWELS.has(w[i + 1] ?? '')) out += 'и'
    else out += LETTERS[ch] ?? ch
    i++
  }
  return out.charAt(0).toUpperCase() + out.slice(1)
}

export function transliterate(text) {
  return text.replace(/[A-Za-zÀ-ž']+/g, (w) => (w === "'" ? '' : transliterateWord(w.replace(/'/g, ''))))
}
